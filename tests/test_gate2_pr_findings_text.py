"""Gate 2's text after the PR opens: the sections the main session follows to
wait for checks, triage what the PR carries, fix, and merge.

Text pins, not behaviour -- the script behind it is tests/test_ship_pr_findings.py.
They read `plugins/cai` (the source) and, for the one thing Codex says
differently, `plugins/cai-codex` (generated by scripts/gen-codex.py).
"""
import os
import re

import pytest

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
GATES = os.path.join("skills", "track", "references", "approval-gates.md")

SUBSECTIONS = ["Inside a track: who runs what", "After the PR opens",
               "The triage menu", "A fix round", "The merge menu"]


def _read(plugin_root):
    with open(os.path.join(ROOT, plugin_root, GATES), encoding="utf-8") as fh:
        return fh.read()


def _gate2(plugin_root="plugins/cai"):
    text = _read(plugin_root)
    start = text.index("\n## Gate 2")
    return text[start + 1:text.index("\n## ", start + 1)]


def _sub(title, plugin_root="plugins/cai"):
    gate = _gate2(plugin_root)
    start = gate.index("\n### " + title + "\n")
    end = gate.find("\n### ", start + 1)
    return gate[start + 1:end if end != -1 else len(gate)]


def _flat(text):
    return " ".join(text.split())


def _table_rows(section):
    return [ln for ln in section.splitlines() if ln.startswith("| ")]


def test_gate_2_is_still_one_section_with_the_five_subsections_in_order():
    text = _read("plugins/cai")
    assert len(re.findall(r"^## Gate 2", text, re.M)) == 1
    gate = _gate2()
    positions = [gate.index("\n### " + t + "\n") for t in SUBSECTIONS]
    assert positions == sorted(positions)
    # No second `## Gate` heading and the subsections sit before the other stops.
    assert "## The other stops" in text[text.index("### The merge menu"):]


def test_the_who_runs_what_table_names_every_command_and_its_runner():
    rows = _flat("\n".join(_table_rows(_sub(SUBSECTIONS[0]))))
    for command in ("git fetch origin", "preflight.py ship", "gh pr create",
                    "gh pr edit", "ship_pr_findings.py", "gh pr merge"):
        assert command in rows
    assert "shipper" in rows and "verify" in rows
    assert "bash guard" in rows


def test_standing_alone_says_findings_are_not_checked():
    text = _flat(_gate2())
    assert ("Standing alone does not look at the pull request's review "
            "threads or check annotations either") in text


def test_run_them_inside_a_track_no_longer_covers_the_merge():
    text = _flat(_gate2())
    assert "quotes and runs only the push and the `gh pr create` or " \
           "`gh pr edit`" in text
    assert "or `gh pr edit` that carries a drafted PR body" in text


def test_after_the_pr_opens_records_then_runs_the_script_in_slices():
    sec = _flat(_sub(SUBSECTIONS[1]))
    assert "Left open: merge menu not answered (PR #<n>)" in sec
    assert "--gate human" in sec
    assert sec.index("--gate human") < sec.index("ship_pr_findings.py")
    assert "--track-dir .claude/track/<feature>" in sec
    assert "Exit 8" in sec and "--started-at" in sec and "wait_started_at" in sec
    assert "finding-severity.md" in sec
    assert "fix_rounds" in sec
    assert "OPEN" in sec and "--gate auto" in sec  # someone else closed it


def test_the_triage_list_format_carries_what_the_person_needs_to_judge():
    sec = _sub(SUBSECTIONS[1])
    flat = _flat(sec)
    assert "[Major]" in sec and "Reason:" in sec
    assert "path:line" in flat and "review thread" in flat
    assert "check annotation" in flat
    assert "`no fix`" in flat
    assert "Minor" in flat and "finding-severity.md" in flat
    # It opens with the script's own checks line, re-lookup sentence included.
    assert "checks" in flat and "still no check runs after a <N> s re-look" in flat
    assert "unchecked" in flat


def test_triage_menu_has_one_recommended_option_and_a_cap():
    sec = _sub(SUBSECTIONS[2])
    rows = _table_rows(sec)
    assert any(r.startswith("| Fix every Blocker/Major (recommended)")
               for r in rows)
    assert any(r.startswith("| Fix none") for r in rows)
    assert sum("(recommended)" in r for r in rows) == 1
    flat = _flat(sec)
    assert "committed to this branch" in flat
    assert "list numbers" in flat
    assert "Minor" in flat and "unchecked" in flat  # not valid picks


